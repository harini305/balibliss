// Collects the `notes` recorded in every content/pages/*.js file (corrections, source
// conflicts, open questions) plus the contact audit into docs/content-review.md.
// Usage: node scripts/review-notes.mjs
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = resolve(import.meta.dirname, '..');
const dir = resolve(ROOT, 'content/pages');
const files = (await readdir(dir)).filter((f) => f.endsWith('.js')).sort();
const audit = JSON.parse(await readFile(resolve(ROOT, 'content/contact-audit.json'), 'utf8'));

let md = `# Content review notes\n\nGenerated by \`node scripts/review-notes.mjs\` from the notes recorded while transcribing balibliss.net (checked ${audit.checked}). Nothing here is shown on the site. Each item needs an owner decision or confirmation.\n\n`;
md += `## Contact details: conflicts found on the live site\n\n${audit.conflicts.map((c) => `- ${c}`).join('\n')}\n\n`;
md += `The new site follows the live site's behaviour: enquiry and booking WhatsApp links use +62 813-3659-182, and the footer WhatsApp icon uses +62 815-8641-7127.\n\n## Pages\n\n`;
for (const f of files) {
  const page = (await import(pathToFileURL(resolve(dir, f)).href)).default;
  if (!page.notes?.length) continue;
  md += `### ${page.title} — \`/${page.slug}/\`\n\n${page.notes.map((n) => `- ${n}`).join('\n')}\n\n`;
}
await writeFile(resolve(ROOT, 'docs/content-review.md'), md);
console.log(`docs/content-review.md: ${files.length} pages scanned`);
